const APP = window.spurt?.name || "";
let LANG = "en";

export function setLang(lang) {
  LANG = STRINGS[lang] ? lang : "en";
  document.documentElement.lang = LANG;
}

export const lang = () => LANG;

export function t(key, ...args) {
  const v = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  const out = typeof v === "function" ? v(...args) : v;
  return typeof out === "string" ? out.replaceAll("{app}", APP) : out;
}

/** "Friday 27 November" / "Freitag, 27. November", from a YYYY-MM-DD date. */
export function longDate(iso, length = "long") {
  const d = new Date(iso + "T12:00:00");
  return new Intl.DateTimeFormat(LANG === "de" ? "de-CH" : "en-GB", {
    weekday: length,
    day: "numeric",
    month: length,
  }).format(d);
}
